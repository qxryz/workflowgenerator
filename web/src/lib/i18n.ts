function interpolate(message: string, values?: TranslationValues) {
    if (!values) return message;
    return message.replace(/\{(\w+)\}/g, (placeholder, key: string) => (Object.hasOwn(values, key) ? String(values[key]) : placeholder));
}

export function translate(language: AppLanguage, message: string, values?: TranslationValues) {
    const template = language === "en-US" ? englishMessages[message] || message : message;
    return interpolate(template, values);
}

export function isEnglish(language: AppLanguage) {
    return language === "en-US";
}
